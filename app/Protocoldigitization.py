def get_body_paragraph_format(doc: Document, start_paragraph: Paragraph):
    """Find the first non-heading paragraph after start_paragraph and return its format."""
    # Traverse from start_paragraph onward
    current = start_paragraph._element
    while current is not None:
        next_elem = current.getnext()
        if next_elem is not None and next_elem.tag.endswith('p'):
            next_para = Paragraph(next_elem, doc)
            # Skip empty paragraphs and headings (you can customize heading detection)
            if next_para.text.strip() and not next_para.style.name.startswith('Heading'):
                return next_para.paragraph_format
        current = next_elem
    return None

def insert_text_block_after(parent, index, text: str, doc: Document, source_para: Paragraph):
    lines = [text.strip()]
    
    # Get formatting from a nearby body paragraph (not the heading)
    body_format = get_body_paragraph_format(doc, source_para)
    
    for line in lines:
        new_p = OxmlElement("w:p")
        parent.insert(index + 1, new_p)
        para = Paragraph(new_p, doc)
        
        # Apply body paragraph formatting (spacing, line spacing, etc.)
        if body_format:
            # Copy all paragraph formatting EXCEPT left/right indent (we want heading margins)
            if body_format.alignment is not None:
                para.paragraph_format.alignment = body_format.alignment
            if body_format.line_spacing_rule is not None:
                para.paragraph_format.line_spacing_rule = body_format.line_spacing_rule
            if body_format.line_spacing is not None:
                para.paragraph_format.line_spacing = body_format.line_spacing
            if body_format.space_before is not None:
                para.paragraph_format.space_before = body_format.space_before
            if body_format.space_after is not None:
                para.paragraph_format.space_after = body_format.space_after
            # Also copy other properties like widow/orphan control if needed
        
        # Copy left/right indent from the heading (source_para) to match margins
        if source_para.paragraph_format.left_indent is not None:
            para.paragraph_format.left_indent = source_para.paragraph_format.left_indent
        if source_para.paragraph_format.right_indent is not None:
            para.paragraph_format.right_indent = source_para.paragraph_format.right_indent
        if source_para.paragraph_format.first_line_indent is not None:
            para.paragraph_format.first_line_indent = source_para.paragraph_format.first_line_indent
        
        # Add runs with bold support
        pos = 0
        for match in BOLD_PATTERN.finditer(line):
            start, end = match.span()
            if start > pos:
                para.add_run(line[pos:start])
            run = para.add_run(match.group(1))
            run.bold = True
            pos = end
        if pos < len(line):
            para.add_run(line[pos:])
        
        index += 1
    return index



def insert_section_blocks_into_document(doc: Document, placeholder: str, blocks):
    target_paragraph = None
    for p in doc.element.body.iter():
        if not p.tag.endswith("p"):
            continue
        texts = [t.text for t in p.iter() if t.text]
        if not texts:
            continue
        full_text = "".join(texts)
        if placeholder in full_text:
            target_paragraph = Paragraph(p, doc)
            break

    if target_paragraph is None:
        print(f"⚠️ Section marker not found: {placeholder}")
        return

    parent = target_paragraph._element.getparent()
    index = parent.index(target_paragraph._element)

    # remove marker text
    for node in target_paragraph._element.iter():
        if node.tag.endswith("}t"):
            if node.text and placeholder in node.text:
                node.text = node.text.replace(placeholder, "")

    for block_type, content in blocks:
        if not content.strip():
            continue
        if block_type == "text":
            # Pass the source_para (target_paragraph) to preserve formatting
            index = insert_text_block_after(parent, index, content, doc, target_paragraph)
        elif block_type == "table":
            table = build_word_table_from_pipe_text(doc, content)
            parent.insert(index + 1, table._element)
            index += 1


def render_all_sections():
    if not FINAL_SECTION_BUFFER:
        raise ValueError("No sections added. Nothing to populate.")

    prefix = normalize_prefix(INDEX_PREFIX)

    blob_service = BlobServiceClient.from_connection_string(
        AZURE_BLOB_CONN_STRING
    )
    container = blob_service.get_container_client(BLOB_CONTAINER)

    template_blob_path = f"{prefix}/{TEMPLATE_NAME}"
    template_blob = container.get_blob_client(template_blob_path)

    if not template_blob.exists():
        raise FileNotFoundError(f"Template not found: {template_blob_path}")

    template_bytes = template_blob.download_blob().readall()

    tpl = DocxTemplate(BytesIO(template_bytes))

    context = {}
    table_sections = {}

    # ---------------------------------
    # 1️⃣ Build context dynamically
    # ---------------------------------

    for section_name, llm_text in FINAL_SECTION_BUFFER.items():
        template_var = SECTION_TO_TEMPLATE_VAR.get(section_name)
        if not template_var:
            continue

        blocks = split_into_blocks(llm_text)

        section_marker = f"__SECTION_{template_var}__"
        context[template_var] = section_marker
        table_sections[section_marker] = blocks

    # ---------------------------------
    # 2️⃣ First pass render (docxtpl)
    # ---------------------------------

    tpl.render(context)

    temp_stream = BytesIO()
    tpl.save(temp_stream)
    temp_stream.seek(0)

    # ---------------------------------
    # 3️⃣ Second pass (python-docx)
    # ---------------------------------

    doc = Document(temp_stream)

    for marker, blocks in table_sections.items():
        insert_section_blocks_into_document(doc, marker, blocks)

    final_stream = BytesIO()
    doc.save(final_stream)
    final_stream.seek(0)

    output_blob_path = f"{prefix}/{OUTPUT_NAME}"
    output_blob = container.get_blob_client(output_blob_path)
    output_blob.upload_blob(final_stream, overwrite=True)

    print("✅ CSR populated successfully with dynamic table detection")
