BOLD_PATTERN = re.compile(r"\*\*(.*?)\*\*")

def markdown_to_richtext(text: str) -> RichText:
    rt = RichText()
    pos = 0
    for match in BOLD_PATTERN.finditer(text):
        start, end = match.span()
        if start > pos:
            rt.add(text[pos:start])
        rt.add(match.group(1), bold=True)
        pos = end
    if pos < len(text):
        rt.add(text[pos:])
    return rt

